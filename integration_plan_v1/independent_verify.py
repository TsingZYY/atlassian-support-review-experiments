"""Independent source audit; never imports or executes experiment.py.

Uses standard-library CSV parsing and residual SSE for R2. Bootstrap intervals
and permutation p-values are not independently regenerated by this verifier.
"""
from __future__ import annotations

import calendar
import csv
import hashlib
import json
import math
from collections import Counter, defaultdict
from pathlib import Path
from statistics import fmean, median


HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"
CHECKS: list[str] = []


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def check(name, actual, expected):
    if isinstance(expected, bool):
        assert actual is expected, (name, actual, expected)
    elif isinstance(expected, (int, float)):
        assert math.isclose(actual, expected, rel_tol=1e-10, abs_tol=1e-10), (
            name, actual, expected
        )
    else:
        assert actual == expected, (name, actual, expected)
    CHECKS.append(name)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sorted_hash(ids, salt):
    return sorted(ids, key=lambda cid: hashlib.sha256(f"{salt}|{cid}".encode()).hexdigest())


def grouped_r2(rows, metric):
    """Fit category means, then calculate 1 - residual SSE / total SSE."""
    groups = defaultdict(list)
    for row in rows:
        groups[row["plan"]].append(row[metric])
    fitted = {plan: fmean(values) for plan, values in groups.items()}
    overall = fmean(row[metric] for row in rows)
    residual = math.fsum((row[metric] - fitted[row["plan"]]) ** 2 for row in rows)
    total = math.fsum((row[metric] - overall) ** 2 for row in rows)
    return 1 - residual / total


def main():
    protocol = json.loads((HERE / "protocol.json").read_text(encoding="utf-8"))
    published = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
    lock = json.loads((HERE / "execution_lock.json").read_text(encoding="utf-8"))
    for filename, expected in lock["source_sha256"].items():
        check(f"source hash {filename}", sha(DATA / filename), expected)
        check(f"results source hash {filename}", published["source_sha256"][filename], expected)
    for filename, expected in lock["protocol_code_sha256"].items():
        check(f"frozen hash {filename}", sha(HERE / filename), expected)
        check(f"results frozen hash {filename}", published["protocol_code_sha256"][filename], expected)

    customer_rows = read_csv(DATA / "customers.csv")
    usage_rows = read_csv(DATA / "product_usage.csv")
    customers = {row["Customer ID"]: row for row in customer_rows}
    check("unique customer IDs", len(customers), len(customer_rows))
    check("unique normalized emails", len({row["Customer Email"].strip().lower() for row in customer_rows}), len(customer_rows))
    check("customer missing cells", sum(value == "" for row in customer_rows for value in row.values()), 0)
    check("usage missing cells", sum(value == "" for row in usage_rows for value in row.values()), 0)
    check("plan labels", sorted({row["Plan Type"] for row in customer_rows}), sorted(protocol["plans"]))
    check("product labels", sorted({row["Product"] for row in usage_rows}), sorted(protocol["products"]))

    customer_source_rows = {row["Customer ID"]: i for i, row in enumerate(customer_rows, 2)}
    by_customer, by_pair = defaultdict(list), defaultdict(list)
    monthly = defaultdict(list)
    triples = set()
    bad_customers = set()
    bad_days, bad_numeric, unmatched, duplicate = 0, 0, 0, 0
    raw_metrics = ["Integrations Used", "Active Days", "Sessions", "Product Actions", "Collaborators"]
    normalized_rows = []
    for source_row, raw in enumerate(usage_rows, 2):
        cid = raw["Customer ID"]
        if cid not in customers:
            unmatched += 1
            continue
        triplet = (cid, raw["Product"], raw["Month"])
        duplicate += triplet in triples
        triples.add(triplet)
        numeric = {metric: float(raw[metric]) for metric in raw_metrics}
        bad_numeric += sum(not math.isfinite(value) or value < 0 or not value.is_integer() for value in numeric.values())
        year, month = map(int, raw["Month"].split("-"))
        days = calendar.monthrange(year, month)[1]
        if numeric["Active Days"] > days:
            bad_days += 1
            bad_customers.add(cid)
        row = dict(numeric, customer_id=cid, product=raw["Product"], month=raw["Month"],
                   plan=customers[cid]["Plan Type"], source_row=source_row)
        row["Active Day Rate"] = numeric["Active Days"] / days
        normalized_rows.append(row)
        by_customer[cid].append(row)
        by_pair[(cid, row["product"])].append(row)
        monthly[row["month"]].append(row)

    aggregate = {}
    for cid, records in by_customer.items():
        aggregate[cid] = {metric: fmean(row[metric] for row in records) for metric in protocol["metrics"]}
        aggregate[cid].update(customer_id=cid, plan=customers[cid]["Plan Type"])
    all_customers = list(aggregate.values())
    common = [row for row in all_customers if row["customer_id"] not in bad_customers]
    independent_quality = {
        "source_customers": len(customer_rows), "source_usage_rows": len(usage_rows),
        "customer_product_pairs": len(by_pair), "unmatched_usage_ids": unmatched,
        "customers_without_usage": len(set(customers) - set(by_customer)),
        "duplicate_customer_product_months": duplicate,
        "incomplete_five_month_pairs": sum(sorted(row["month"] for row in records) != protocol["months"] for records in by_pair.values()),
        "invalid_numeric_counts": bad_numeric,
        "active_days_exceed_calendar_rows": bad_days,
        "active_days_exceed_calendar_customers": len(bad_customers),
        "customer_product_counts": dict(Counter(str(len({r["product"] for r in records})) for records in by_customer.values())),
        "primary_customer_n": len(all_customers), "common_metrics_customer_n": len(common),
    }
    for key, value in independent_quality.items():
        check(f"quality {key}", value, published["quality"][key])

    primary = grouped_r2(all_customers, "Integrations Used")
    check("primary residual SSE R2", primary, published["primary"]["eta_squared_ols_r2"])
    ranking = {metric: grouped_r2(common, metric) for metric in protocol["metrics"]}
    for comparison in published["common_cohort_metric_ranking"]["comparisons"]:
        check(f"common {comparison['metric']} R2", ranking[comparison["metric"]], comparison["eta_squared_ols_r2"])
        check(f"common {comparison['metric']} n", len(common), comparison["customer_n"])
    gap = ranking["Integrations Used"] - max(value for metric, value in ranking.items() if metric != "Integrations Used")
    check("integration gap", gap, published["common_cohort_metric_ranking"]["integration_minus_largest_other"])
    check("integration rank first", gap > 0, published["common_cohort_metric_ranking"]["integration_is_largest"])
    check("raw row R2", grouped_r2(normalized_rows, "Integrations Used"), published["raw_product_month_descriptive_r2"])
    for item in published["monthly_descriptive_r2"]:
        rows = monthly[item["month"]]
        check(f"month {item['month']} n", len(rows), item["product_customer_rows"])
        check(f"month {item['month']} R2", grouped_r2(rows, "Integrations Used"), item["eta_squared_ols_r2"])

    product_results = []
    for product in protocol["products"]:
        values = [{"plan": customers[cid]["Plan Type"], "Integrations Used": fmean(row["Integrations Used"] for row in records)}
                  for (cid, prod), records in by_pair.items() if prod == product]
        result = {"product": product, "customer_n": len(values), "eta_squared_ols_r2": grouped_r2(values, "Integrations Used")}
        expected = next(item for item in published["product_sensitivity"] if item["product"] == product)
        for key, value in result.items():
            check(f"product {product} {key}", value, expected[key])
        product_results.append(result)

    zeros = {"zero_product_month_records": sum(row["Integrations Used"] == 0 for row in normalized_rows),
             "product_month_denominator": len(normalized_rows),
             "any_zero_record_customers": sum(any(row["Integrations Used"] == 0 for row in records) for records in by_customer.values()),
             "all_records_zero_customers": sum(all(row["Integrations Used"] == 0 for row in records) for records in by_customer.values()),
             "customer_denominator": len(by_customer)}
    for key, value in zeros.items():
        check(f"zero usage {key}", value, published["zero_usage"][key])
    independent_plans = []
    for plan in protocol["plans"]:
        ids = [cid for cid in customers if customers[cid]["Plan Type"] == plan]
        records = [row for cid in ids for row in by_customer[cid]]
        values = [aggregate[cid]["Integrations Used"] for cid in ids]
        result = {"plan": plan, "customer_n": len(ids), "mean_customer_integrations": fmean(values),
                  "median_customer_integrations": median(values),
                  "any_zero_record_customers": sum(any(row["Integrations Used"] == 0 for row in by_customer[cid]) for cid in ids),
                  "all_records_zero_customers": sum(all(row["Integrations Used"] == 0 for row in by_customer[cid]) for cid in ids),
                  "product_month_records": len(records), "zero_product_month_records": sum(row["Integrations Used"] == 0 for row in records)}
        expected = next(item for item in published["plan_summary"] if item["plan"] == plan)
        for key, value in result.items():
            check(f"plan {plan} {key}", value, expected[key])
        independent_plans.append(result)

    train, test, split_counts, fitted = [], [], [], {}
    for plan in protocol["plans"]:
        ids = sorted_hash([cid for cid in customers if customers[cid]["Plan Type"] == plan], protocol["holdout_hash_salt"])
        cutoff = math.floor(len(ids) * protocol["training_fraction"])
        train += ids[:cutoff]
        test += ids[cutoff:]
        fitted[plan] = fmean(aggregate[cid]["Integrations Used"] for cid in ids[:cutoff])
        split_counts.append({"plan": plan, "train_n": cutoff, "test_n": len(ids) - cutoff})
    check("holdout all customers assigned", set(train) | set(test), set(customers))
    check("holdout no shared customer", len(set(train) & set(test)), 0)
    observed = [aggregate[cid]["Integrations Used"] for cid in test]
    predictions = [fitted[aggregate[cid]["plan"]] for cid in test]
    train_mean, test_mean = fmean(aggregate[cid]["Integrations Used"] for cid in train), fmean(observed)
    mse = fmean((y - p) ** 2 for y, p in zip(observed, predictions))
    baseline = fmean((y - train_mean) ** 2 for y in observed)
    holdout = {"train_n": len(train), "test_n": len(test), "by_plan": split_counts,
               "trained_plan_means": fitted, "training_global_mean": train_mean,
               "test_r2": 1 - mse / fmean((y - test_mean) ** 2 for y in observed),
               "test_mse": mse, "training_global_mean_baseline_test_mse": baseline,
               "mse_reduction_vs_training_global_mean": 1 - mse / baseline}
    for key, value in holdout.items():
        if key == "trained_plan_means":
            for plan, mean in value.items():
                check(f"holdout fitted mean {plan}", mean, published["customer_holdout"][key][plan])
        else:
            check(f"holdout {key}", value, published["customer_holdout"][key])

    audit = read_csv(HERE / "audit_cases_20.csv")
    expected_audit = []
    for plan in protocol["plans"]:
        expected_audit += sorted_hash([cid for cid in customers if customers[cid]["Plan Type"] == plan], protocol["audit_hash_salt"])[:protocol["audit_per_plan"]]
    check("source audit selection order", [row["customer_id"] for row in audit], expected_audit)
    check("source audit count", len(audit), 20)
    check("source audit unique customers", len({row["customer_id"] for row in audit}), 20)
    for index, row in enumerate(audit, 1):
        cid = row["customer_id"]
        records = by_customer[cid]
        prefix = f"source audit {index}"
        check(f"{prefix} customer row", int(row["customer_source_row"]), customer_source_rows[cid])
        check(f"{prefix} plan", row["plan"], customers[cid]["Plan Type"])
        check(f"{prefix} usage rows", [int(x) for x in row["usage_source_rows"].split("|")], [r["source_row"] for r in records])
        check(f"{prefix} product count", int(row["product_n"]), len({r["product"] for r in records}))
        check(f"{prefix} record count", int(row["usage_record_n"]), len(records))
        for metric in protocol["metrics"]:
            check(f"{prefix} {metric}", float(row[metric]), aggregate[cid][metric])
        check(f"{prefix} zero count", int(row["zero_record_n"]), sum(r["Integrations Used"] == 0 for r in records))
        check(f"{prefix} all zero", row["all_records_zero"] == "True", all(r["Integrations Used"] == 0 for r in records))
        check(f"{prefix} common eligible", row["common_metric_eligible"] == "True", cid not in bad_customers)

    for filename, key in [("plan_summary.csv", "plan_summary"), ("product_sensitivity.csv", "product_sensitivity"),
                          ("usage_metric_comparison.csv", "common_cohort_metric_ranking")]:
        csv_rows = read_csv(HERE / filename)
        result_rows = published[key]["comparisons"] if key == "common_cohort_metric_ranking" else published[key]
        check(f"artifact {filename} n", len(csv_rows), len(result_rows))
        for i, (csv_row, result_row) in enumerate(zip(csv_rows, result_rows)):
            for field, expected in result_row.items():
                actual = float(csv_row[field]) if isinstance(expected, (int, float)) else csv_row[field]
                check(f"artifact {filename} row {i + 1} {field}", actual, expected)

    result = {"status": "PASS", "independent_method": "standard_library_csv_group_means_residual_sse_r2",
              "never_imports_or_executes_main_experiment": True,
              "initial_point_estimates_computed_before_reading_main_results": True,
              "bootstrap_intervals_independently_regenerated": False,
              "permutation_p_value_independently_regenerated": False,
              "source_sha256": {filename: sha(DATA / filename) for filename in lock["source_sha256"]},
              "independent_verifier_sha256": sha(Path(__file__)),
              "quality": independent_quality, "primary_r2": primary, "common_metric_r2": ranking,
              "product_sensitivity": product_results, "plan_summary": independent_plans,
              "customer_holdout": holdout, "zero_usage": zeros,
              "source_audit_customers_verified": len(audit), "check_count": len(CHECKS), "checks": CHECKS}
    (HERE / "independent_audit.json").write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    markdown = f"""# 集成使用与套餐：独立复算

状态：**PASS**。完成 {len(CHECKS)} 项断言，来源核对20/20客户。

## 独立实现与范围

`independent_verify.py` 直接用标准库读取比赛CSV，以组均值拟合后计算 `R² = 1 - 残差平方和 / 总平方和`。不调用、不导入主实验脚本。首次点估计、粒度与零值核对在读取主实验结果前完成；本验证器随后与主实验结果进行逐项比较。

已独立复算客户聚合、共同队列、五指标排名、分产品与月份的R²、固定哈希客户训练/测试分割、训练套餐均值、测试MSE及标准测试R²、各套餐零使用口径，以及20名核对客户的原始CSV行号与全部聚合值。核对源文件和冻结协议/主代码哈希、三个结果CSV与JSON一致性。

**Bootstrap区间和置换p值未由此验证器独立重生成。** CSV中这些区间只核对与主JSON一致，不能声称其随机复算独立通过。

## 复算结果

- 集成主队列8,320客户，R²={primary:.12f}。
- 五指标共同队列8,261客户；仅此比较排除Active Days超过日历天数的59名客户（85条记录）。集成R²={ranking['Integrations Used']:.12f}，其他四项最高为Sessions {ranking['Sessions']:.12f}。
- 客户哈希分割训练{len(train):,}、测试{len(test):,}，客户无交叉；测试R²={holdout['test_r2']:.12f}，MSE={mse:.12f}，训练全局均值基线MSE={baseline:.12f}。
- 零使用共有3,979条产品月记录、2,424名客户至少一条零记录，但只有4名客户全部产品、全部五个月记录均零。
- 所有套餐、产品与月份的点估计与主结果在1e-10容差内一致。

解释仅限当前合成样本中的关联与内部复核。套餐为类别预测变量，R²描述套餐对集成使用量方差的解释比例；集成在固定五项使用指标中关联最强，不等于全部因素中的独立重要性。没有月度套餐变更、集成尝试/失败及原因字段，不能解释少用原因或证明提高集成使用会增加付费、升级、留存与利润。

复跑：`python integration_plan_v1/independent_verify.py`。
"""
    (HERE / "independent_audit.md").write_text(markdown, encoding="utf-8", newline="\n")
    print(f"INTEGRATION_INDEPENDENT_AUDIT_PASS checks={len(CHECKS)} customers={len(all_customers)} source_audit={len(audit)}")


if __name__ == "__main__":
    main()
